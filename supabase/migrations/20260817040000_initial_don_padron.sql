create extension if not exists pgcrypto with schema extensions;

create schema if not exists private;
revoke all on schema private from public, anon, authenticated;

create table public.products (
  id text primary key,
  name text not null,
  description text not null default '',
  category text not null,
  unit text not null,
  price_cup integer not null check (price_cup >= 0),
  stock numeric(12, 3) not null default 0 check (stock >= 0),
  minimum_step numeric(12, 3) not null default 1 check (minimum_step > 0),
  emoji text not null default '🥩',
  accent text not null default '#d92525',
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index products_active_category_idx
  on public.products (active, category, name);

create table public.orders (
  id uuid primary key default gen_random_uuid(),
  display_id text not null unique,
  customer_name text not null,
  phone text not null,
  delivery_method text not null check (delivery_method in ('recoger', 'domicilio')),
  address text not null default '',
  payment_method text not null check (payment_method in ('Transfermóvil', 'Efectivo')),
  notes text not null default '',
  total_cup integer not null check (total_cup >= 0),
  status text not null default 'pendiente'
    check (status in ('pendiente', 'confirmado', 'pagado', 'listo', 'completado', 'cancelado')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index orders_status_created_idx
  on public.orders (status, created_at desc);

create table public.order_items (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id text not null references public.products(id),
  product_name text not null,
  quantity numeric(12, 3) not null check (quantity > 0),
  unit text not null,
  price_each_cup integer not null check (price_each_cup >= 0),
  subtotal_cup integer not null check (subtotal_cup >= 0)
);

create index order_items_order_id_idx on public.order_items (order_id);

create table public.settings (
  id text primary key,
  business_name text not null,
  whatsapp_phone text not null default '',
  pickup_address text not null default '',
  payment_copy text not null default '',
  updated_at timestamptz not null default now()
);

create table private.admin_credentials (
  id text primary key,
  password_hash text not null,
  session_hours integer not null default 168 check (session_hours between 1 and 720),
  updated_at timestamptz not null default now()
);

create table private.admin_sessions (
  id uuid primary key default gen_random_uuid(),
  token_hash text not null unique,
  expires_at timestamptz not null,
  created_at timestamptz not null default now()
);

create index admin_sessions_expires_at_idx on private.admin_sessions (expires_at);

