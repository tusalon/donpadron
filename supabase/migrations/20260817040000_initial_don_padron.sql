create or replace function private.has_admin_session(p_token text)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select
    p_token is not null
    and length(p_token) = 64
    and exists (
      select 1
      from private.admin_sessions s
      where s.token_hash = encode(extensions.digest(p_token, 'sha256'), 'hex')
        and s.expires_at > now()
    );
$$;

revoke all on function private.has_admin_session(text) from public, anon, authenticated;

create or replace function public.get_catalog()
returns jsonb
language sql
stable
security definer
set search_path = ''
as $$
  select jsonb_build_object(
    'products', coalesce((
      select jsonb_agg(
        jsonb_build_object(
          'id', p.id,
          'name', p.name,
          'description', p.description,
          'category', p.category,
          'unit', p.unit,
          'priceCup', p.price_cup,
          'stock', p.stock,
          'minimumStep', p.minimum_step,
          'emoji', p.emoji,
          'accent', p.accent
        ) order by p.category, p.name
      )
      from public.products p
      where p.active
    ), '[]'::jsonb),
    'settings', coalesce((
      select jsonb_build_object(
        'businessName', s.business_name,
        'whatsappPhone', s.whatsapp_phone,
        'pickupAddress', s.pickup_address,
        'paymentCopy', s.payment_copy
      )
      from public.settings s
      where s.id = 'main'
    ), '{}'::jsonb)
  );
$$;

create or replace function public.place_order(p_payload jsonb)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_customer_name text := btrim(coalesce(p_payload ->> 'customerName', ''));
  v_phone text := btrim(coalesce(p_payload ->> 'phone', ''));
  v_delivery_method text := btrim(coalesce(p_payload ->> 'deliveryMethod', 'recoger'));
  v_address text := btrim(coalesce(p_payload ->> 'address', ''));
  v_payment_method text := btrim(coalesce(p_payload ->> 'paymentMethod', 'Efectivo'));
  v_notes text := left(btrim(coalesce(p_payload ->> 'notes', '')), 300);
  v_items jsonb := p_payload -> 'items';
  v_item jsonb;
  v_product public.products%rowtype;
  v_product_id text;
  v_quantity numeric(12, 3);
  v_subtotal integer;
  v_total integer := 0;
  v_order_id uuid := gen_random_uuid();
  v_display_id text;
  v_seen text[] := array[]::text[];
  v_settings public.settings%rowtype;
begin
  if v_customer_name = '' or length(regexp_replace(v_phone, '\D', '', 'g')) < 8 then
    raise exception using errcode = '22023', message = 'Escribe tu nombre y un teléfono válido.';
  end if;

  if v_delivery_method not in ('recoger', 'domicilio') then
    raise exception using errcode = '22023', message = 'Forma de entrega inválida.';
  end if;

  if v_delivery_method = 'domicilio' and v_address = '' then
    raise exception using errcode = '22023', message = 'Escribe la dirección de entrega.';
  end if;

  if v_payment_method not in ('Transfermóvil', 'Efectivo') then
    raise exception using errcode = '22023', message = 'Forma de pago inválida.';
  end if;

  if jsonb_typeof(v_items) <> 'array'
     or jsonb_array_length(v_items) < 1
     or jsonb_array_length(v_items) > 20 then
    raise exception using errcode = '22023', message = 'Añade al menos un producto al pedido.';
  end if;

  v_display_id := 'DP-' || upper(substr(replace(v_order_id::text, '-', ''), 1, 6));

  insert into public.orders
    (id, display_id, customer_name, phone, delivery_method, address,
     payment_method, notes, total_cup)
  values
    (v_order_id, v_display_id, v_customer_name, v_phone, v_delivery_method,
     v_address, v_payment_method, v_notes, 0);

  for v_item in
    select value
    from jsonb_array_elements(v_items)
    order by value ->> 'productId'
  loop
    v_product_id := btrim(coalesce(v_item ->> 'productId', ''));

    if v_product_id = '' or jsonb_typeof(v_item -> 'quantity') <> 'number' then
      raise exception using errcode = '22023', message = 'Revisa los productos del pedido.';
    end if;

    v_quantity := (v_item ->> 'quantity')::numeric;

    if v_quantity <= 0 or v_product_id = any(v_seen) then
      raise exception using errcode = '22023', message = 'Revisa las cantidades del pedido.';
    end if;
    v_seen := array_append(v_seen, v_product_id);

    select * into v_product
    from public.products
    where id = v_product_id
    for update;

    if not found or not v_product.active then
      raise exception using errcode = 'P0001', message = 'Uno de los productos ya no está disponible.';
    end if;

    if v_quantity > v_product.stock then
      raise exception using errcode = 'P0001',
        message = format('Solo quedan %s de %s.', v_product.stock, v_product.name);
    end if;

    if abs((v_quantity / v_product.minimum_step) - round(v_quantity / v_product.minimum_step)) > 0.0001 then
      raise exception using errcode = '22023', message = format('Revisa la cantidad de %s.', v_product.name);
    end if;

    v_subtotal := round(v_product.price_cup * v_quantity)::integer;
    v_total := v_total + v_subtotal;

    insert into public.order_items
      (order_id, product_id, product_name, quantity, unit, price_each_cup, subtotal_cup)
    values
      (v_order_id, v_product.id, v_product.name, v_quantity, v_product.unit,
       v_product.price_cup, v_subtotal);

    update public.products
    set stock = stock - v_quantity, updated_at = now()
    where id = v_product.id;
  end loop;

  update public.orders
  set total_cup = v_total, updated_at = now()
  where id = v_order_id;

  select * into v_settings from public.settings where id = 'main';

  return jsonb_build_object(
    'order', jsonb_build_object(
      'id', v_order_id,
      'displayId', v_display_id,
      'totalCup', v_total
    ),
    'settings', jsonb_build_object(
      'whatsappPhone', coalesce(v_settings.whatsapp_phone, ''),
      'pickupAddress', coalesce(v_settings.pickup_address, ''),
      'paymentCopy', coalesce(v_settings.payment_copy, '')
    )
  );
end;
$$;

create or replace function public.admin_login(p_password text)
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_hash text;
  v_hours integer;
  v_token text;
begin
  if p_password is null or length(p_password) < 8 or length(p_password) > 256 then
    perform pg_sleep(0.35);
    return null;
  end if;

  select password_hash, session_hours into v_hash, v_hours
  from private.admin_credentials
  where id = 'main';

  if v_hash is null or extensions.crypt(p_password, v_hash) <> v_hash then
    perform pg_sleep(0.35);
    return null;
  end if;

  delete from private.admin_sessions where expires_at <= now();
  v_token := encode(extensions.gen_random_bytes(32), 'hex');

  insert into private.admin_sessions (token_hash, expires_at)
  values (
    encode(extensions.digest(v_token, 'sha256'), 'hex'),
    now() + make_interval(hours => v_hours)
  );

  return v_token;
end;
$$;

create or replace function public.admin_logout(p_token text)
returns void
language sql
security definer
set search_path = ''
as $$
  delete from private.admin_sessions
  where token_hash = encode(extensions.digest(coalesce(p_token, ''), 'sha256'), 'hex');
$$;

create or replace function public.admin_dashboard(p_token text)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not private.has_admin_session(p_token) then
    raise exception using errcode = '42501', message = 'La sesión administrativa venció.';
  end if;

  return jsonb_build_object(
    'products', coalesce((
      select jsonb_agg(
        jsonb_build_object(
          'id', p.id,
          'name', p.name,
          'category', p.category,
          'unit', p.unit,
          'priceCup', p.price_cup,
          'stock', p.stock,
          'minimumStep', p.minimum_step,
          'emoji', p.emoji,
          'active', p.active
        ) order by p.category, p.name
      )
      from public.products p
    ), '[]'::jsonb),
    'orders', coalesce((
      select jsonb_agg(
        jsonb_build_object(
          'id', o.id,
          'displayId', o.display_id,
          'customerName', o.customer_name,
          'phone', o.phone,
          'deliveryMethod', o.delivery_method,
          'address', o.address,
          'paymentMethod', o.payment_method,
          'notes', o.notes,
          'totalCup', o.total_cup,
          'status', o.status,
          'createdAt', o.created_at,
          'items', coalesce((
            select jsonb_agg(
              jsonb_build_object(
                'id', i.id,
                'productId', i.product_id,
                'productName', i.product_name,
                'quantity', i.quantity,
                'unit', i.unit,
                'priceEachCup', i.price_each_cup,
                'subtotalCup', i.subtotal_cup
              ) order by i.id
            )
            from public.order_items i
            where i.order_id = o.id
          ), '[]'::jsonb)
        ) order by o.created_at desc
      )
      from (
        select * from public.orders order by created_at desc limit 80
      ) o
    ), '[]'::jsonb),
    'settings', coalesce((
      select jsonb_build_object(
        'businessName', s.business_name,
        'whatsappPhone', s.whatsapp_phone,
        'pickupAddress', s.pickup_address,
        'paymentCopy', s.payment_copy
      )
      from public.settings s
      where s.id = 'main'
    ), '{}'::jsonb)
  );
end;
$$;

create or replace function public.admin_update_product(
  p_token text,
  p_product_id text,
  p_stock numeric,
  p_price_cup integer,
  p_active boolean
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not private.has_admin_session(p_token) then
    raise exception using errcode = '42501', message = 'La sesión administrativa venció.';
  end if;
  if p_product_id is null or p_stock < 0 or p_price_cup < 0 then
    raise exception using errcode = '22023', message = 'Revisa el precio y la existencia.';
  end if;

  update public.products
  set stock = p_stock,
      price_cup = p_price_cup,
      active = coalesce(p_active, true),
      updated_at = now()
  where id = p_product_id;

  if not found then
    raise exception using errcode = 'P0002', message = 'Producto no encontrado.';
  end if;
end;
$$;

create or replace function public.admin_update_order(
  p_token text,
  p_order_id uuid,
  p_status text
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_current_status text;
begin
  if not private.has_admin_session(p_token) then
    raise exception using errcode = '42501', message = 'La sesión administrativa venció.';
  end if;
  if p_status not in ('pendiente', 'confirmado', 'pagado', 'listo', 'completado', 'cancelado') then
    raise exception using errcode = '22023', message = 'Estado de pedido inválido.';
  end if;

  select status into v_current_status
  from public.orders
  where id = p_order_id
  for update;

  if not found then
    raise exception using errcode = 'P0002', message = 'Pedido no encontrado.';
  end if;
  if v_current_status = 'cancelado' and p_status <> 'cancelado' then
    raise exception using errcode = 'P0001', message = 'Un pedido cancelado no puede reabrirse automáticamente.';
  end if;

  if p_status = 'cancelado' and v_current_status <> 'cancelado' then
    update public.products p
    set stock = p.stock + i.quantity,
        updated_at = now()
    from public.order_items i
    where i.order_id = p_order_id and i.product_id = p.id;
  end if;

  update public.orders
  set status = p_status, updated_at = now()
  where id = p_order_id;
end;
$$;

create or replace function public.admin_update_settings(
  p_token text,
  p_business_name text,
  p_whatsapp_phone text,
  p_pickup_address text,
  p_payment_copy text
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_phone text := regexp_replace(coalesce(p_whatsapp_phone, ''), '\D', '', 'g');
begin
  if not private.has_admin_session(p_token) then
    raise exception using errcode = '42501', message = 'La sesión administrativa venció.';
  end if;
  if btrim(coalesce(p_business_name, '')) = ''
     or btrim(coalesce(p_pickup_address, '')) = ''
     or btrim(coalesce(p_payment_copy, '')) = '' then
    raise exception using errcode = '22023', message = 'Completa los datos del negocio.';
  end if;
  if v_phone <> '' and length(v_phone) < 10 then
    raise exception using errcode = '22023',
      message = 'Escribe el número de WhatsApp con código de país.';
  end if;

  update public.settings
  set business_name = btrim(p_business_name),
      whatsapp_phone = v_phone,
      pickup_address = btrim(p_pickup_address),
      payment_copy = btrim(p_payment_copy),
      updated_at = now()
  where id = 'main';
end;
$$;

create or replace function public.admin_import_legacy_order(p_token text, p_order jsonb)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_order_id uuid;
  v_item jsonb;
  v_inserted integer;
begin
  if not private.has_admin_session(p_token) then
    raise exception using errcode = '42501', message = 'La sesión administrativa venció.';
  end if;

  v_order_id := (p_order ->> 'id')::uuid;
  insert into public.orders
    (id, display_id, customer_name, phone, delivery_method, address,
     payment_method, notes, total_cup, status, created_at, updated_at)
  values
    (v_order_id, p_order ->> 'displayId', p_order ->> 'customerName',
     p_order ->> 'phone', p_order ->> 'deliveryMethod', coalesce(p_order ->> 'address', ''),
     p_order ->> 'paymentMethod', coalesce(p_order ->> 'notes', ''),
     (p_order ->> 'totalCup')::integer, p_order ->> 'status',
     (p_order ->> 'createdAt')::timestamptz, (p_order ->> 'createdAt')::timestamptz)
  on conflict (id) do nothing;
  get diagnostics v_inserted = row_count;

  if v_inserted = 0 then
    return;
  end if;

  for v_item in select value from jsonb_array_elements(coalesce(p_order -> 'items', '[]'::jsonb))
  loop
    insert into public.order_items
      (order_id, product_id, product_name, quantity, unit, price_each_cup, subtotal_cup)
    values
      (v_order_id, v_item ->> 'productId', v_item ->> 'productName',
       (v_item ->> 'quantity')::numeric, v_item ->> 'unit',
       (v_item ->> 'priceEachCup')::integer, (v_item ->> 'subtotalCup')::integer);
  end loop;
end;
$$;

